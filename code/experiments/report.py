"""Aggregate canonical experiment JSONL files into JSON, CSV, and LaTeX."""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

from experiments.metrics import summarize_episodes


def load_jsonl(paths: list[Path]) -> list[dict]:
    rows = []
    for path in paths:
        with path.open(encoding="utf-8") as stream:
            rows.extend(json.loads(line) for line in stream if line.strip())
    return rows


def aggregate(rows: list[dict]) -> list[dict]:
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for row in rows:
        groups[(row["method"], row["scenario"])].append(row)
    return [summarize_episodes(group) for _, group in sorted(groups.items())]


def write_outputs(summaries: list[dict], output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "summary.json").write_text(
        json.dumps(summaries, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    flat_rows = []
    for item in summaries:
        row = {"method": item["method"], "scenario": item["scenario"], "n": item["n"]}
        for metric, stats in item["metrics"].items():
            for stat, value in stats.items():
                row[f"{metric}_{stat}"] = value
        flat_rows.append(row)
    if flat_rows:
        with (output_dir / "summary.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(flat_rows[0]))
            writer.writeheader()
            writer.writerows(flat_rows)
    (output_dir / "phase1_results.tex").write_text(_latex_table(summaries), encoding="utf-8")


def _latex_table(summaries: list[dict]) -> str:
    lines = [
        "% Generated by python -m experiments.report; do not edit.",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Method & Scenario & Success (\\%) & Collision (\\%) & RMS (mm) & Clearance (cm) \\\\",
        "\\midrule",
    ]
    for item in summaries:
        m = item["metrics"]
        lines.append(
            f"{item['method']} & {item['scenario']} & "
            f"{100*m['success']['mean']:.1f} & {100*m['collision']['mean']:.1f} & "
            f"{1000*m['tracking_rms_m']['mean']:.2f} & {100*m['min_clearance_m']['mean']:.2f} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    write_outputs(aggregate(load_jsonl(args.inputs)), args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
